/**
 * Generates products/index.ts (the list of products, from the products/<id>/
 * folders) and renders the readable product sheets, docs/products/<id>.md. Both
 * are generated and committed: Jesse reads the sheets, Claude changes the
 * product files.
 *
 *   npm run products:render              write products/index.ts, then the sheets
 *   npm run products:render -- --check   exit 1 if the index or any sheet is out of date
 *
 * A new product is one folder, products/<id>/, whose index.ts exports
 * `<camelCaseId>` (e.g. products/bss-custom/index.ts exports `bssCustom`).
 * Running this registers it: no other file changes.
 *
 * A custom product (defineCustomProduct, products/custom.ts) also gets "Based
 * on", "Spec" and "Draft wording" rows and a "Differences from <base>" section,
 * with notes on inherited wording that quotes days when its timeline changed.
 */
import { existsSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
// No import of products/index.ts (or products/load.ts, which imports it): this
// script rewrites that file, so it must still run when the file names a folder
// that was just deleted or renamed. The product list is passed in, or loaded
// after the index is written.
import { allSteps, dueDaysFor, stepTree, stepVisibleFor, teamTasksFor, type StageNode } from "../../products/helpers";
import type { ClientStep, CustomDerivation, Product, ProductStage, ProductVariant, TeamTask } from "../../products/types";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const PRODUCTS_DIR = join(ROOT, "products");
const INDEX_PATH = join(PRODUCTS_DIR, "index.ts");

// ── products/index.ts ─────────────────────────────────────────────────────

/** The sheet order of the first products; any other product follows alphabetically. */
const FIRST = ["scale", "respond", "bss", "website"];

/** "bss-custom" → "bssCustom": the name a product folder's index.ts must export. */
export function camelCase(id: string): string {
  return id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
}

/** Every products/<id>/ folder with an index.ts, in sheet order. */
export function scanProductIds(): string[] {
  const ids = readdirSync(PRODUCTS_DIR).filter((name) => {
    const dir = join(PRODUCTS_DIR, name);
    return statSync(dir).isDirectory() && existsSync(join(dir, "index.ts"));
  });
  const first = FIRST.filter((id) => ids.includes(id));
  const rest = ids.filter((id) => !FIRST.includes(id)).sort();
  return [...first, ...rest];
}

/** The generated products/index.ts for these product folders (in sheet order). */
export function renderProductIndex(ids: string[]): string {
  const names = ids.map(camelCase);
  const imports = [...ids].sort().map((id) => `import { ${camelCase(id)} } from "./${id}";`);
  return [
    "// GENERATED by scripts/products/render.ts (npm run products:render). Do not edit.",
    "// A product is a folder products/<id>/ whose index.ts exports `<camelCaseId>`. See docs/products/README.md.",
    "",
    ...imports,
    'import type { ClientTypeOf, Product } from "./types";',
    "",
    `export { ${[...names].sort().join(", ")} };`,
    "",
    "/** Every product, in sheet order. */",
    `export const productList = [${names.join(", ")}] as const satisfies readonly Product[];`,
    "",
    "/** Every client type a product file defines (live, paused or draft). */",
    "export type ClientType = ClientTypeOf<(typeof productList)[number]>;",
    "",
  ].join("\n");
}

/** True when products/index.ts is what the folders say it should be. */
export function indexCurrent(): boolean {
  return existsSync(INDEX_PATH) && readFileSync(INDEX_PATH, "utf8") === renderProductIndex(scanProductIds());
}

// ── Sheets ────────────────────────────────────────────────────────────────

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
const code = (id: string) => `\`${id}\``;
const channelLabel = (channels?: readonly string[]) =>
  !channels || channels.length === 0 ? "" : channels.length === 1 ? `${channels[0] === "meta" ? "Meta" : "Google"} only` : channels.join(" + ");

function stageDays(stage: ProductStage): string {
  if (stage.teamOnly && stage.ongoing) return "team only, as needed";
  const days = stage.dayStart === stage.dayEnd ? `day ${stage.dayStart}` : `days ${stage.dayStart}–${stage.dayEnd}`;
  if (stage.teamOnly) return `team only, ${days}`;
  return stage.ongoing ? `${days} on, ongoing` : days;
}

function dueLabel(task: TeamTask): string {
  const days = dueDaysFor(task);
  if (!days) return task.due;
  return task.dueDays ? `${task.due} (days ${days.start}–${days.end})` : task.due;
}

/** What the portal asks of the client on this step, in a few words. */
function stepKinds(step: ClientStep): string[] {
  const kinds: string[] = [];
  if (step.interviewAgentId || step.interview) kinds.push("voice interview");
  if (step.formId) kinds.push(`form \`${step.formId}\``);
  if (step.bookingUrl) kinds.push("booking calendar");
  if (step.hasUpload) kinds.push("upload");
  if (step.hasEditableContent) kinds.push("work to review");
  if (step.notePrompt) kinds.push(step.noteRequired ? "note (required)" : "note");
  else if (step.noteRequired) kinds.push("answer required");
  if (step.videoUrl) kinds.push("video");
  if (step.guideUrl) kinds.push("guide link");
  if (step.embedUrl) kinds.push("embedded form");
  if (step.steps) kinds.push(`${step.steps.length} numbered steps`);
  if (step.inviteEmail) kinds.push("invite email");
  if (step.showPortalLink) kinds.push("portal link");
  if (step.important) kinds.push("\"Important\" box");
  if (step.awaitingTeam) kinds.push("shown as with the team");
  return kinds;
}

function taskRow(task: TeamTask, stepStage?: string): string {
  const marks: string[] = [];
  const channels = channelLabel(task.channels);
  if (channels) marks.push(channels);
  if (stepStage && task.stage !== stepStage) marks.push(`team stage: ${task.stage}`);
  if (task.completesWithSteps) marks.push(`done when the client finishes ${task.completesWithSteps.map(code).join(", ")}`);
  const title = `${code(task.id)} ${cell(task.title)}${marks.length ? ` _(${marks.join("; ")})_` : ""}`;
  const after = task.dependencies.length ? task.dependencies.map(code).join(", ") : "";
  return `| ${title} | ${cell(task.role)} | ${cell(dueLabel(task))} | ${task.priority} | ${after} |`;
}

function guidance(tasks: TeamTask[], L: string[]) {
  const withNotes = tasks.filter((t) => t.notes.trim());
  if (!withNotes.length) return;
  L.push("");
  L.push(`<details><summary>Guidance for the team (${withNotes.length} ${withNotes.length === 1 ? "task" : "tasks"})</summary>`);
  L.push("");
  for (const t of withNotes) {
    L.push(`**${code(t.id)} ${t.title}**`);
    L.push("");
    L.push(t.notes.trim());
    L.push("");
  }
  L.push("</details>");
}

function taskTable(tasks: TeamTask[], L: string[], stepStage?: string) {
  L.push("| Team task | Role | Due | Priority | After |");
  L.push("|---|---|---|---|---|");
  for (const t of tasks) L.push(taskRow(t, stepStage));
  guidance(tasks, L);
}

function variantTweaks(variant: ProductVariant): string[] {
  const p = variant.portal;
  const lines: string[] = [];
  const look: string[] = [];
  if (p.brandName) look.push(`named **${p.brandName}**`);
  if (p.tagline) look.push(`tagline "${p.tagline}"`);
  if (p.lockedLook) look.push(`look fixed to \`${p.lockedLook}\``);
  if (p.hidesIncentive) look.push("no $200 \"move fast\" popup");
  if (look.length) lines.push(`- ${look.join(" · ")}`);
  if (p.introVideo) lines.push(`- Intro video after "Get started": "${p.introVideo.title}" (\`${p.introVideo.src}\`)`);
  for (const [id, note] of Object.entries(p.taskNotes ?? {})) lines.push(`- Note on ${code(id)}: "${note}"`);
  for (const [id, detail] of Object.entries(p.taskDetails ?? {})) lines.push(`- Description of ${code(id)} replaced with: "${detail}"`);
  const hidden: string[] = [];
  if (p.hiddenTaskVideos?.length) hidden.push(`video on ${p.hiddenTaskVideos.map(code).join(", ")}`);
  if (p.hiddenTaskBooking?.length) hidden.push(`booking calendar on ${p.hiddenTaskBooking.map(code).join(", ")}`);
  if (p.hiddenTaskPlayground?.length) hidden.push(`live AI test on ${p.hiddenTaskPlayground.map(code).join(", ")}`);
  if (p.hiddenTaskImportant?.length) hidden.push(`"Important" box on ${p.hiddenTaskImportant.map(code).join(", ")}`);
  if (hidden.length) lines.push(`- Hidden: ${hidden.join("; ")}`);
  if (p.hiddenGuideStages?.length) lines.push(`- Voice guide hidden on ${p.hiddenGuideStages.map(code).join(", ")}`);
  if (p.stringPlan) lines.push(`- String Theory: ${p.stringPlan.workstreams.length} strands, go-live day ${p.stringPlan.goLiveDay}`);
  return lines;
}

/** Whether new clients can start on this variant. */
function offeredLabel(product: Product, variant: ProductVariant): string {
  if (variant.offered === false) return "no";
  if (product.status === "live") return "yes";
  if (product.status === "draft") return "where PRODUCT_DRAFTS=1";
  return "no";
}

/** The product's portal settings: name, voice guide, Ask-AI, step features. */
function portalSettings(product: Product): string[] {
  const portal = product.portal;
  if (!portal) return ["None: no client type runs on this product."];
  const L: string[] = ["| | |", "|---|---|"];
  L.push(`| Name the client sees | **${cell(portal.wordmark)}**, unless a variant sets its own name |`);
  const guide = portal.voiceGuide;
  const guideStages = guide ? Object.entries(guide.scripts).filter(([, script]) => Boolean(script)).map(([stage]) => stage) : [];
  L.push(`| Voice guide | ${guide && guideStages.length ? `${guideStages.map(code).join(", ")} (audio \`public/portal/voice/${guide.audioPrefix}-<stage>.m4a\`)` : "off"} |`);
  const ask = Object.entries(portal.askAi ?? {}).filter(([, items]) => items && items.length);
  L.push(`| Ask-AI | ${ask.length ? ask.map(([stage, items]) => `${code(stage)} (${items!.length})`).join(", ") : "off"} |`);
  const f = portal.features ?? {};
  const features: string[] = [];
  if (f.playgroundSteps?.length) features.push(`live AI receptionist test on ${f.playgroundSteps.map(code).join(", ")}`);
  if (f.receptionistScriptStep) features.push(`receptionist script from ${code(f.receptionistScriptStep)}`);
  if (f.landingPreviewSteps?.length) features.push(`landing-page preview on ${f.landingPreviewSteps.map(code).join(", ")}`);
  if (f.nonBlockingSteps?.length) features.push(`never blocking: ${f.nonBlockingSteps.map(code).join(", ")}`);
  L.push(`| Step features | ${features.length ? features.join("; ") : "none"} |`);
  return L;
}

// ── Custom products ───────────────────────────────────────────────────────

/** Client wording that quotes a day ("day 14", "Days 1-2", "30-day"). */
const QUOTES_DAYS = /\bdays?\s*\d|\d+-day/i;

/** The client-facing text fields of a step, by field name. */
function stepTexts(step: ClientStep): [string, string][] {
  const out: [string, string | undefined][] = [
    ["title", step.title],
    ["detail", step.detail],
    ["notePrompt", step.notePrompt],
    ["notePlaceholder", step.notePlaceholder],
    ["embedTitle", step.embedTitle],
    ["embedNote", step.embedNote],
    ["guideLabel", step.guideLabel],
    ["important", step.important],
    ["inviteEmail", step.inviteEmail],
    ["doneLabel", step.doneLabel],
    ...(step.steps ?? []).map((text, i) => [`steps[${i + 1}]`, text] as [string, string]),
    ...(step.interview ?? []).map((text, i) => [`interview[${i + 1}]`, text] as [string, string]),
  ];
  return out.filter((entry): entry is [string, string] => Boolean(entry[1]));
}

/** The base a custom product was derived from, when it is one of these products. */
function baseProductOf(custom: CustomDerivation, products: readonly Product[]): Product | null {
  if (custom.base === "blank") return null;
  const id = custom.base.id;
  return products.find((p) => p.id === id) ?? null;
}

/** "Scale 2026-10-17.1 (meta)", or "a blank product". */
function baseName(custom: CustomDerivation): string {
  if (custom.base === "blank") return "a blank product";
  return `${custom.base.name} ${custom.base.version}${custom.base.variant !== undefined ? ` (${custom.base.variant})` : ""}`;
}

const excerpt = (text: string) => {
  const flat = text.replace(/\s+/g, " ").trim();
  return flat.length > 140 ? `${flat.slice(0, 137)}…` : flat;
};

/**
 * Copy lint for a custom product whose timeline changed: inherited client
 * wording (not added, not changed by the spec) that quotes days, which may now
 * be wrong. Notes only: a person decides. Empty when the timeline is the base's.
 */
export function copyLintNotes(product: Product, products: readonly Product[] = []): string[] {
  const custom = product.custom;
  if (!custom || !custom.timelineChanged || custom.base === "blank") return [];
  const added = new Set(custom.addedSteps);
  const changed = new Map(custom.changedSteps.map((c) => [c.id, new Set(c.fields)]));
  const base = baseProductOf(custom, products);
  const notes: string[] = [];
  const flag = (where: string, text: string) => {
    if (QUOTES_DAYS.test(text)) notes.push(`${where} still says "${excerpt(text)}": check the days against this product's timeline`);
  };
  for (const stage of product.stages.filter((s) => !s.teamOnly)) {
    const from = base?.stages.find((s) => s.id === stage.id);
    if (base && !from) continue; // a stage the custom product added: its own wording
    if (!from || from.name === stage.name) flag(`stage ${stage.id} name`, stage.name);
    if (stage.blurb && (!from || from.blurb === stage.blurb)) flag(`stage ${stage.id} blurb`, stage.blurb);
    for (const note of stage.statusNotes) if (!from || from.statusNotes.includes(note)) flag(`stage ${stage.id} status note`, note);
  }
  for (const step of allSteps(product)) {
    if (added.has(step.id) || step.hidden || !product.variants.some((v) => stepVisibleFor(step, v))) continue;
    const own = changed.get(step.id) ?? new Set<string>();
    const replacedDetail = product.variants.some((v) => v.portal.taskDetails && Object.hasOwn(v.portal.taskDetails, step.id));
    for (const [field, text] of stepTexts(step)) {
      const root = field.replace(/\[\d+\]$/, "");
      if (own.has(root) || (field === "detail" && replacedDetail)) continue;
      flag(`${code(step.id)} ${field}`, text);
    }
  }
  return notes;
}

const listOr = (items: string[], none = "none") => (items.length ? items.join(", ") : none);

/** The sheet's "Differences" section for a custom product. */
function differencesSection(product: Product, custom: CustomDerivation, products: readonly Product[]): string[] {
  const L: string[] = [];
  const base = baseProductOf(custom, products);
  if (custom.base === "blank") {
    L.push("## Differences: written from scratch");
    L.push("");
    L.push("No base: every step and task below is this product's own.");
    L.push("");
    return L;
  }
  const from = custom.base.name;
  L.push(`## Differences from ${baseName(custom)}`);
  L.push("");
  L.push(`Worked out by \`defineCustomProduct\` from \`products/${product.id}/index.ts\`. Everything not listed here is ${from}'s, as it is${custom.base.variant !== undefined ? ` for its \`${custom.base.variant}\` variant` : ""}.`);
  L.push("");
  L.push("| | |");
  L.push("|---|---|");
  L.push(`| Steps removed | ${listOr(custom.removedSteps.map(code))} |`);
  L.push(`| Steps changed | ${listOr(custom.changedSteps.map((c) => `${code(c.id)} (${c.fields.join(", ")})`))} |`);
  L.push(`| Steps added | ${listOr(custom.addedSteps.map(code))} |`);
  L.push(`| Team tasks removed | ${listOr(custom.removedTasks.map((t) => `${code(t.id)} (${cell(t.reason)})`))} |`);
  L.push(`| Team tasks changed | ${listOr(custom.changedTasks.map((c) => `${code(c.id)} (${c.fields.join(", ")})`))} |`);
  L.push(`| Team tasks added | ${listOr(custom.addedTasks.map(code))} |`);
  L.push(`| Dependencies dropped | ${listOr(custom.droppedDependencies.map((d) => `${code(d.task)} no longer waits on ${code(d.dependsOn)}`))} |`);
  const setting = (key: "voiceGuide" | "askAi" | "features", present: boolean) =>
    custom.inherited[key] ? `inherited from ${from}` : present ? "its own" : "off";
  L.push(`| Voice guide | ${setting("voiceGuide", Boolean(product.portal?.voiceGuide))} |`);
  L.push(`| Ask-AI | ${setting("askAi", Boolean(product.portal?.askAi && Object.keys(product.portal.askAi).length))} |`);
  L.push(`| Step features | ${setting("features", Boolean(product.portal?.features))} |`);
  L.push(`| Timeline | ${custom.timelineChanged ? "changed (below)" : `${from}'s, unchanged`} |`);
  L.push("");
  if (custom.timelineChanged) {
    L.push("### Timeline");
    L.push("");
    L.push(`| | ${from} | This product |`);
    L.push("|---|---|---|");
    L.push(`| Days to go-live | ${base?.totalDays ?? "?"} | ${product.totalDays ?? "not set"} |`);
    const ids = [...new Set([...(base?.stages.map((s) => s.id) ?? []), ...product.stages.map((s) => s.id)])];
    for (const id of ids) {
      const a = base?.stages.find((s) => s.id === id);
      const b = product.stages.find((s) => s.id === id);
      L.push(`| ${cell((b ?? a)!.name)} | ${a ? stageDays(a) : "no such stage"} | ${b ? stageDays(b) : "dropped"} |`);
    }
    L.push("");
    const notes = copyLintNotes(product, products);
    L.push("### Wording to check");
    L.push("");
    if (notes.length) {
      L.push(`The timeline changed, and this inherited client wording quotes days. Each line is a note, not an error: fix the wording in \`steps.change\`, or leave it if it is still right.`);
      L.push("");
      for (const n of notes) L.push(`- ${n}`);
    } else {
      L.push("No inherited client wording quotes a day.");
    }
    L.push("");
  }
  return L;
}

function stageSection(node: StageNode, index: number, L: string[]) {
  const { stage } = node;
  L.push(`## ${index + 1}. ${stage.name} · ${stageDays(stage)}`);
  L.push("");
  if (stage.blurb) {
    L.push(`_${stage.blurb}_`);
    L.push("");
  }
  if (stage.statusNotes.length) {
    L.push(`Status notes the client sees: ${stage.statusNotes.map((n) => `"${n}"`).join(" · ")}`);
    L.push("");
  }
  for (const { step, tasks, alsoCompletedBy } of node.steps) {
    const marks: string[] = [];
    if (step.hidden) marks.push("hidden in the portal");
    const channels = channelLabel(step.channels);
    if (channels) marks.push(channels);
    if (step.clientOnly) marks.push("client only");
    L.push(`### ${code(step.id)} ${step.title}${marks.length ? ` _(${marks.join(", ")})_` : ""}`);
    L.push("");
    L.push(`> ${cell(step.detail)}`);
    L.push("");
    const kinds = stepKinds(step);
    if (kinds.length) {
      L.push(`Portal: ${kinds.join(" · ")}`);
      L.push("");
    }
    if (step.clientOnly && !tasks.length && !alsoCompletedBy.length) {
      L.push("No team task behind this step.");
      L.push("");
      continue;
    }
    if (alsoCompletedBy.length) {
      L.push(`Done with: ${alsoCompletedBy.map((t) => `${code(t.id)} (behind ${code(t.step ?? "")})`).join(", ")}`);
      L.push("");
    }
    if (tasks.length) {
      taskTable(tasks, L, stage.id);
      L.push("");
    }
  }
  if (node.teamOnly.length) {
    L.push(stage.teamOnly ? `### Team work` : `### Team-only work in ${stage.name}`);
    L.push("");
    const byCategory = new Map<string, TeamTask[]>();
    for (const t of node.teamOnly) byCategory.set(t.category, [...(byCategory.get(t.category) ?? []), t]);
    L.push("| Team task | Role | Due | Priority | After |");
    L.push("|---|---|---|---|---|");
    for (const [category, tasks] of byCategory) {
      L.push(`| **${cell(category)}** | | | | |`);
      for (const t of tasks) L.push(taskRow(t));
    }
    guidance(node.teamOnly, L);
    L.push("");
  }
  if (!node.steps.length && !node.teamOnly.length) {
    L.push("Nothing here yet.");
    L.push("");
  }
}

/** A product's sheet. `products` (the product files) is where a custom product's base is looked up. */
export function renderSheet(product: Product, products: readonly Product[] = []): string {
  const L: string[] = [];
  const steps = allSteps(product);
  const behind = product.teamTasks.filter((t) => t.step).length;
  L.push(`<!-- GENERATED by scripts/products/render.ts from products/${product.id}/. Do not edit: ask Claude to change the product files, then run npm run products:render. -->`);
  L.push("");
  L.push(`# ${product.name}`);
  L.push("");
  L.push(`> **Generated sheet. Ask Claude to change it.** Source: \`products/${product.id}/\`. How changes work: [README](README.md).`);
  L.push("");
  L.push("| | |");
  L.push("|---|---|");
  L.push(`| Version | \`${product.version}\` |`);
  const statusText: Record<Product["status"], string> = {
    live: "live: new clients start on it",
    paused: "paused: existing clients keep it; never offered for new clients or put on a board",
    draft: "draft: offered and put on boards only where PRODUCT_DRAFTS=1",
  };
  L.push(`| Status | ${statusText[product.status]} |`);
  L.push(`| Journey | ${product.totalDays === null ? "timeline not set yet" : `${product.totalDays} days to go-live`} |`);
  if (steps.length) {
    const clientOnly = steps.filter((s) => s.clientOnly).length;
    const hidden = steps.filter((s) => s.hidden).length;
    L.push(`| Client steps | ${steps.length} (${clientOnly} client only, ${hidden} hidden in the portal) |`);
  } else {
    L.push("| Client steps | none in this product file |");
  }
  L.push(`| Team tasks | ${product.teamTasks.length} (${behind} behind a client step, ${product.teamTasks.length - behind} team-only) |`);
  const custom = product.custom;
  if (custom) {
    L.push(`| Based on | ${custom.base === "blank" ? "nothing: written from scratch" : `${custom.base.name} \`${custom.base.version}\`${custom.base.variant !== undefined ? `, variant \`${custom.base.variant}\`` : ""}`} |`);
    L.push(`| Spec | [${custom.spec}](../../${custom.spec}) |`);
    L.push(`| Draft wording | ${custom.draftCopy.length ? `${custom.draftCopy.map(code).join(", ")}: Claude drafted this wording; Jesse approves it before the product goes live` : "none: every client-facing word is approved"} |`);
  } else {
    const reportLink = product.source.report.replace(/^docs\/products\//, "");
    L.push(`| Converted from | ${product.source.from} at \`${product.source.commit}\` on ${product.source.convertedOn}: [conversion report](${reportLink}), with [open questions for Jesse](${reportLink}#flags-for-jesse-not-fixed) |`);
  }
  if (product.source.document) L.push(`| Source document | [${cell(product.source.document.title)}](${product.source.document.url}) |`);
  L.push("");
  if (product.variants.length && steps.length) {
    L.push("The portal reads this file. `npm run check:journeys` freezes what each client type sees.");
    L.push("");
  }

  // Differences (custom products)
  if (custom) L.push(...differencesSection(product, custom, products));

  // Variants
  L.push("## Variants");
  L.push("");
  if (!product.variants.length) {
    L.push("None. No client type runs on this product.");
    L.push("");
  } else {
    L.push("| Variant | Client type | Channels | Offered | Client steps shown | Team tasks |");
    L.push("|---|---|---|---|---|---|");
    for (const v of product.variants) {
      const shown = steps.filter((s) => stepVisibleFor(s, v)).length;
      L.push(`| ${cell(v.label)} | ${code(v.clientType)} | ${v.channels?.join(", ") ?? "none"} | ${offeredLabel(product, v)} | ${shown} | ${teamTasksFor(product, v).length} |`);
    }
    L.push("");
    const tweaked = product.variants.filter((v) => Object.keys(v.portal).length);
    if (tweaked.length) {
      L.push("### Portal tweaks by variant");
      L.push("");
      for (const v of tweaked) {
        L.push(`**${v.label}** (${code(v.clientType)})`);
        L.push("");
        L.push(...variantTweaks(v));
        L.push("");
      }
    }
  }

  // Portal settings
  L.push("## Portal settings");
  L.push("");
  L.push(...portalSettings(product));
  L.push("");

  // Roles
  L.push("## Roles");
  L.push("");
  L.push("| Role | Team tasks |");
  L.push("|---|---|");
  for (const role of product.roles) L.push(`| ${cell(role)} | ${product.teamTasks.filter((t) => t.role === role).length} |`);
  L.push("");

  // Stages
  L.push("## Stages");
  L.push("");
  L.push("Each stage lists the client's steps in portal order, with the team tasks behind each step, then any team-only work. _Meta only_ / _Google only_ marks work for one ad channel. \"After\" lists the tasks to finish first.");
  L.push("");
  stepTree(product).forEach((node, i) => stageSection(node, i, L));

  return L.join("\n").replace(/\n{3,}/g, "\n\n").trimEnd() + "\n";
}

/** Every generated sheet for these products, by repo-relative path. */
export function renderSheets(products: readonly Product[]): Record<string, string> {
  return Object.fromEntries(products.map((p) => [`docs/products/${p.id}.md`, renderSheet(p, products)]));
}

const SHEET_MARK = "<!-- GENERATED by scripts/products/render.ts from products/";

/** Generated sheets in docs/products/ whose product folder is gone. */
function orphanSheets(ids: readonly string[]): string[] {
  const dir = join(ROOT, "docs", "products");
  return readdirSync(dir)
    .filter((name) => name.endsWith(".md") && !ids.includes(name.slice(0, -3)))
    .filter((name) => readFileSync(join(dir, name), "utf8").startsWith(SHEET_MARK))
    .map((name) => `docs/products/${name}`);
}

/** Paths whose committed sheet differs from a fresh render, plus sheets of products that no longer exist. */
export function staleSheets(products: readonly Product[]): string[] {
  const stale = Object.entries(renderSheets(products))
    .filter(([rel, content]) => {
      const path = join(ROOT, rel);
      return !existsSync(path) || readFileSync(path, "utf8") !== content;
    })
    .map(([rel]) => rel);
  return [...stale, ...orphanSheets(products.map((p) => p.id))];
}

/** Writes products/index.ts from the folders, then every sheet, in one run. */
async function writeAll() {
  const ids = scanProductIds();
  const index = renderProductIndex(ids);
  const indexSame = existsSync(INDEX_PATH) && readFileSync(INDEX_PATH, "utf8") === index;
  if (!indexSame) writeFileSync(INDEX_PATH, index);
  console.log(`${indexSame ? "unchanged" : "wrote    "} products/index.ts (${ids.join(", ")})`);
  // Each folder imported directly, so a product added since products/index.ts
  // was last written renders in this same run.
  const products: Product[] = [];
  for (const id of ids) {
    const mod = (await import(pathToFileURL(join(PRODUCTS_DIR, id, "index.ts")).href)) as Record<string, Product | undefined>;
    const product = mod[camelCase(id)];
    if (!product) throw new Error(`products/${id}/index.ts must export \`${camelCase(id)}\``);
    if (product.id !== id) throw new Error(`products/${id}/index.ts exports a product with id "${product.id}": the folder name and the id must match`);
    products.push(product);
  }
  for (const product of products) {
    const rel = `docs/products/${product.id}.md`;
    const path = join(ROOT, rel);
    const content = renderSheet(product, products);
    const same = existsSync(path) && readFileSync(path, "utf8") === content;
    if (!same) writeFileSync(path, content);
    console.log(`${same ? "unchanged" : "wrote    "} ${rel}`);
  }
  // A product folder that was deleted or renamed leaves its generated sheet behind: remove it.
  for (const rel of orphanSheets(ids)) {
    unlinkSync(join(ROOT, rel));
    console.log(`removed   ${rel} (no products/ folder)`);
  }
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1]);
if (isMain) {
  if (process.argv.includes("--check")) {
    // A stale index may name a folder that is gone: report it before loading any product.
    if (!indexCurrent()) {
      console.error("FAIL out of date: products/index.ts. Run npm run products:render.");
      process.exit(1);
    }
    const { productList } = await import("../../products/index");
    const stale = staleSheets(productList);
    if (stale.length) {
      console.error(`FAIL out of date: ${stale.join(", ")}. Run npm run products:render.`);
      process.exit(1);
    }
    console.log(`PASS index and sheets current (${productList.length} sheets).`);
  } else {
    await writeAll();
  }
}
